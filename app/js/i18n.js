const DICT = { ja: {}, es: {}, en: {} };
for (const [key, ja, es] of TABLE) {
  DICT.ja[key] = ja;
  if (es !== undefined && es !== null) DICT.es[key] = es;
}
// English only for keys the table knows, so a stale entry never leaks in.
for (const key of Object.keys(DICT.ja)) if (EN[key] !== undefined && EN[key] !== null) DICT.en[key] = EN[key];

/** Every known key (used by the localization checker and tests). */
export const keys = () => Object.keys(DICT.ja);
/** Raw dictionary for one locale; missing keys fall back to es, then ja, in t(). */
export const dictionary = (loc) => DICT[LOCALES.includes(loc) ? loc : 'ja'];

const format = (s, vars) => (vars
  ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined || vars[k] === null ? m : String(vars[k])))
  : s);

export function getLocale() { return locale; }

export function isSpanish() { return locale === 'es'; }

/** Japanese (the hidden source locale) keeps its own word order and widths. */
export function isJapanese() { return locale === 'ja'; }

const TAGS = { ja: 'ja-JP', es: 'es-ES', en: 'en-US' };
/** BCP-47 tag for Intl/Date formatting. */
export function localeTag() { return TAGS[locale] || 'es-ES'; }

/** Thousands separator and grouping for the current locale. */
export function nf(n) {
  if (!Number.isFinite(n)) return String(n);
  return Number(n).toLocaleString(localeTag());
}

// Current locale, then Spanish, then Japanese: an English player never sees
// Japanese even if a string is still missing.
const lookup = (key) => DICT[locale][key] ?? DICT.es[key] ?? DICT.ja[key];

export function t(key, vars) {
  const s = lookup(key);
  if (s === undefined) return key;
  return format(s, vars);
}

/** t() with a singular/plural pair, keyed "<base>.one" / "<base>.many". */
export function tp(n, base, vars = {}) {
  const suffix = n === 1 ? '.one' : '.many';
  const v = { n, ...vars };
  const s = lookup(base + suffix) ?? lookup(base + '.many');
  return format(s ?? base, v);
}

export function setLocale(next, { persist = true, notify = true } = {}) {
  if (!LOCALES.includes(next) || next === locale) return locale;
  locale = next;
  if (persist) {
    try { globalThis.localStorage?.setItem(STORAGE_KEY, locale); } catch { /* storage may be blocked */ }
  }
  if (notify) {
    applyStatic();
    for (const fn of listeners) { try { fn(locale); } catch { /* a listener must not break the switch */ } }
  }
  return locale;
}

export function onLocaleChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/**
 * Start-up language: `?lang=xx` (the only way to reach Japanese), then the
 * choice saved from Settings, then the device language: any Spanish variant
 * gets Spanish, everything else English.
 */
export function initialLocale(search = globalThis.location?.search || '', nav = globalThis.navigator) {
  const q = new URLSearchParams(search).get('lang');
  if (LOCALES.includes(q)) return q;
  let saved = null;
  try { saved = globalThis.localStorage?.getItem(STORAGE_KEY); } catch { /* storage may be blocked */ }
  if (PUBLIC_LOCALES.includes(saved)) return saved;
  return deviceLocale(nav);
}

/** 'es' for any Spanish device language, otherwise 'en'. */
export function deviceLocale(nav = globalThis.navigator) {
  const langs = [...(nav?.languages || []), nav?.language].filter(Boolean);
  const first = String(langs[0] || '').toLowerCase();
  return first.startsWith('es') ? 'es' : 'en';
}

/** Apply the dictionary to the static HTML (elements tagged with data-i18n*). */
export function applyStatic(root = globalThis.document) {
  if (!root || !root.querySelectorAll) return;
  if (root.documentElement) {
    root.documentElement.lang = locale;
    root.title = t('app.title');
    const desc = root.querySelector('meta[name="description"]');
    if (desc) desc.setAttribute('content', t('app.description'));
  }
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.setAttribute('title', t(el.dataset.i18nTitle)); });
}
